"""SYNTHETIC document generator (fire NOC, affidavit, accreditation, land document, faculty list).

Every document is fictional, carries a "SYNTHETIC" banner, and uses made-up identifiers.
QR codes encode a MOCK issuer reference. Variants deliberately introduce problems so we can
measure what the validators catch.

Used by seed/generate_docs.py and by backend tests.
"""
import io
import json
import random
from dataclasses import dataclass, field
from datetime import date, timedelta

import qrcode
from reportlab.lib.pagesizes import A4
from reportlab.lib.utils import ImageReader
from reportlab.pdfgen import canvas

PAGE_W, PAGE_H = A4
DOC_TYPES = ["fire_noc", "affidavit", "accreditation_certificate", "land_document", "faculty_list"]
VARIANTS = ["valid", "expired", "near_expiry", "missing_field", "name_mismatch", "bad_format", "scanned"]

# Which variants make sense for which doc types.
APPLICABLE = {
    "expired": {"fire_noc", "accreditation_certificate"},
    "near_expiry": {"fire_noc", "accreditation_certificate"},
    "bad_format": {"fire_noc", "accreditation_certificate", "land_document", "affidavit"},
}

# Field each doc type loses in the missing_field variant.
MISSING_FIELD = {
    "fire_noc": "certificate_number",
    "affidavit": "issue_date",
    "accreditation_certificate": "certificate_number",
    "land_document": "certificate_number",
    "faculty_list": "institution_name",
}

# Rule id(s) each variant should trigger on its own (clean institute record assumed).
EXPECTED_RULES = {
    "valid": [],
    "expired": ["EXP-001"],
    "near_expiry": ["EXP-002"],
    "missing_field": ["COMP-002"],
    "name_mismatch": ["CONS-001"],
    "bad_format": ["FMT-001"],
    "scanned": [],
}

MISMATCH_NAME = "SYNTHETIC Riverside College of Arts, Elsewhere Town"
FIRST_NAMES = ["Asha", "Ravi", "Meera", "Arjun", "Kavya", "Nikhil", "Priya", "Rohan", "Sana", "Vikram",
               "Diya", "Kabir", "Isha", "Aman", "Tara", "Dev", "Neha", "Yash", "Anu", "Om"]
SURNAMES = ["Example", "Sample", "Demo", "Testwala", "Placeholder", "Mockingham", "Fictiona"]


@dataclass
class InstitutionData:
    name: str
    address: str
    aicte_ref: str
    state: str
    faculty_count: int


@dataclass
class GeneratedDoc:
    doc_type: str
    variant: str
    pdf: bytes
    truth: dict                      # values printed on the document
    expected_rule_ids: list[str]
    qr_ref: str | None = None
    issuer: str | None = None
    lines: list[tuple[str, str]] = field(default_factory=list)


def fmt(d: date) -> str:
    return d.strftime("%d-%m-%Y")


def _qr_image(payload: dict) -> ImageReader:
    img = qrcode.make(json.dumps(payload, separators=(",", ":")))
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    return ImageReader(buf)


def _render(title: str, subtitle: str, lines: list[tuple[str, str]], body: list[str],
            table: list[list[str]] | None, qr_payload: dict | None) -> bytes:
    buf = io.BytesIO()
    c = canvas.Canvas(buf, pagesize=A4)
    c.setTitle(title)
    c.setFillGray(0.35)
    c.setFont("Helvetica-Bold", 9)
    c.drawCentredString(PAGE_W / 2, PAGE_H - 30, "SYNTHETIC DOCUMENT FOR PROTOTYPE TESTING - NOT A REAL CERTIFICATE")
    c.setFillGray(0)
    c.setFont("Helvetica-Bold", 16)
    c.drawCentredString(PAGE_W / 2, PAGE_H - 70, title)
    c.setFont("Helvetica", 11)
    c.drawCentredString(PAGE_W / 2, PAGE_H - 90, subtitle)

    y = PAGE_H - 140
    c.setFont("Helvetica", 11)
    for label, value in lines:
        c.drawString(60, y, f"{label}: {value}")
        y -= 24
    y -= 10
    for paragraph in body:
        c.drawString(60, y, paragraph)
        y -= 18
    if table:
        y -= 10
        c.setFont("Helvetica-Bold", 10)
        cols = [60, 110, 220, 400]
        for x, head in zip(cols, table[0]):
            c.drawString(x, y, head)
        c.setFont("Helvetica", 10)
        for row in table[1:]:
            y -= 16
            if y < 80:
                c.showPage()
                c.setFont("Helvetica", 10)
                y = PAGE_H - 60
            for x, cell in zip(cols, row):
                c.drawString(x, y, cell)
    if qr_payload:
        c.drawImage(_qr_image(qr_payload), PAGE_W - 150, 60, width=90, height=90)
        c.setFont("Helvetica", 7)
        c.drawString(PAGE_W - 160, 50, "MOCK issuer reference (QR)")
    c.setFont("Helvetica", 8)
    c.setFillGray(0.35)
    c.drawString(60, 40, "Generated by Validex seed tools. Fictional data only.")
    c.save()
    return buf.getvalue()


def make_scanned(pdf: bytes, rng: random.Random) -> bytes:
    """Rasterise a PDF and add scan-like noise: grey, slight rotation, blur, speckle, JPEG."""
    import pypdfium2 as pdfium
    from PIL import Image, ImageFilter

    doc = pdfium.PdfDocument(pdf)
    pages = []
    try:
        for i in range(len(doc)):
            img = doc[i].render(scale=150 / 72).to_pil().convert("L")
            img = img.rotate(rng.uniform(-0.8, 0.8), expand=False, fillcolor=255)
            img = img.filter(ImageFilter.GaussianBlur(0.6))
            px = img.load()
            w, h = img.size
            for _ in range(w * h // 400):  # light speckle noise
                px[rng.randrange(w), rng.randrange(h)] = rng.choice((0, 90, 200))
            jpeg = io.BytesIO()
            img.save(jpeg, format="JPEG", quality=55)
            jpeg.seek(0)
            pages.append(Image.open(jpeg).convert("RGB"))
    finally:
        doc.close()
    out = io.BytesIO()
    pages[0].save(out, format="PDF", save_all=True, append_images=pages[1:], resolution=150)
    return out.getvalue()


def _cert_number(doc_type: str, rng: random.Random, today: date, bad: bool) -> str:
    n6 = f"{rng.randrange(10**6):06d}"
    if doc_type == "fire_noc":
        return f"FNOC/{today.year}/{n6}" if bad else f"FNOC-{today.year}-{n6}"
    if doc_type == "accreditation_certificate":
        return f"ACC-SAB{n6}" if bad else f"ACC-SAB-{n6}"
    if doc_type == "land_document":
        return f"LND-SS-{today.year - 8}-{n6[:4]}" if bad else f"LND-SS-{today.year - 8}-{n6[:5]}"
    if doc_type == "affidavit":
        return f"AFF-{n6}" if bad else f"AFF-{rng.randrange(10**8):08d}"
    return ""


def make_document(doc_type: str, variant: str, inst: InstitutionData, today: date,
                  rng: random.Random, faculty_count: int | None = None) -> GeneratedDoc:
    """Build one synthetic document. `faculty_count` overrides the row count for faculty lists."""
    if variant in APPLICABLE and doc_type not in APPLICABLE[variant]:
        raise ValueError(f"variant {variant} does not apply to {doc_type}")

    name = MISMATCH_NAME if variant == "name_mismatch" else inst.name
    cert = _cert_number(doc_type, rng, today, bad=(variant == "bad_format"))
    issue = today - timedelta(days=rng.randint(120, 400))
    expiry = issue + timedelta(days=3 * 365)
    if variant == "expired":
        expiry = today - timedelta(days=rng.randint(20, 200))
        issue = expiry - timedelta(days=3 * 365)
    elif variant == "near_expiry":
        expiry = today + timedelta(days=rng.randint(20, 70))
        issue = expiry - timedelta(days=3 * 365)

    truth: dict = {"institution_name": name}
    lines: list[tuple[str, str]] = []
    body: list[str] = []
    table = None
    qr = None
    issuer = None

    if doc_type == "fire_noc":
        issuer = "MOCK-FIRE"
        title, subtitle = "FIRE SAFETY NO OBJECTION CERTIFICATE", "SYNTHETIC State Fire Services (MOCK)"
        authority = "Divisional Fire Officer, SYNTHETIC Fire Services"
        lines = [("NOC No", cert), ("Name of Institution", name), ("Address of Premises", inst.address),
                 ("Issuing Authority", authority), ("Date of Issue", fmt(issue)), ("Valid Until", fmt(expiry))]
        body = ["This is to certify that the premises named above were inspected and comply with",
                "the fire safety norms applicable on the date of inspection. (SYNTHETIC)"]
        truth.update(certificate_number=cert, address=inst.address, issuing_authority=authority,
                     issue_date=issue.isoformat(), expiry_date=expiry.isoformat())
        qr = {"issuer": issuer, "ref": cert}
    elif doc_type == "affidavit":
        title, subtitle = "AFFIDAVIT CUM UNDERTAKING", "On non-judicial stamp paper (SYNTHETIC)"
        authority = "Notary Public, Demo District (SYNTHETIC)"
        issue = today - timedelta(days=rng.randint(10, 60))
        lines = [("Affidavit No", cert), ("Name of Institution", name), ("Address", inst.address),
                 ("Attested By", authority), ("Date of Affidavit", fmt(issue))]
        body = ["I, the head of the institution named above, do hereby solemnly affirm that the",
                "information furnished in the application is true to the best of my knowledge."]
        truth.update(certificate_number=cert, address=inst.address, issuing_authority=authority,
                     issue_date=issue.isoformat())
    elif doc_type == "accreditation_certificate":
        issuer = "MOCK-ACCREDITATION"
        title, subtitle = "CERTIFICATE OF ACCREDITATION", "SYNTHETIC Accreditation Board (MOCK)"
        authority = "SYNTHETIC Accreditation Board"
        lines = [("Certificate No", cert), ("Name of Institution", name), ("Programme", "B.Tech (illustrative)"),
                 ("Issuing Authority", authority), ("Date of Issue", fmt(issue)), ("Valid Until", fmt(expiry))]
        body = ["The programme listed above is accredited for the period stated. (SYNTHETIC)"]
        truth.update(certificate_number=cert, issuing_authority=authority,
                     issue_date=issue.isoformat(), expiry_date=expiry.isoformat())
        qr = {"issuer": issuer, "ref": cert}
    elif doc_type == "land_document":
        issuer = "MOCK-LAND-REGISTRY"
        title, subtitle = "LAND REGISTRATION EXTRACT", "Office of the Sub-Registrar (SYNTHETIC)"
        authority = "Sub-Registrar Office, Demo District (SYNTHETIC)"
        issue = today - timedelta(days=rng.randint(2000, 4000))
        area = f"{rng.randint(10, 30)}.{rng.randint(0, 9)}"
        lines = [("Registration No", cert), ("Name of Owner", name), ("Property Address", inst.address),
                 ("Total Area", f"{area} acres"), ("Registering Office", authority),
                 ("Date of Registration", fmt(issue))]
        body = ["Extract of the registered sale deed for the land described above. (SYNTHETIC)"]
        truth.update(certificate_number=cert, address=inst.address, issuing_authority=authority,
                     issue_date=issue.isoformat(), land_area_acres=area)
        qr = {"issuer": issuer, "ref": cert}
    elif doc_type == "faculty_list":
        title, subtitle = "LIST OF FACULTY (TEACHING STAFF)", "Submitted by the institution (SYNTHETIC)"
        count = faculty_count if faculty_count is not None else inst.faculty_count
        issue = today - timedelta(days=rng.randint(5, 30))
        lines = [("Name of Institution", name), ("As On", fmt(issue))]
        rows = [["S.No", "Faculty ID", "Name", "Designation"]]
        ids = []
        for i in range(count):
            fid = f"FAC-{rng.randrange(10**6):06d}"
            ids.append(fid)
            person = f"{rng.choice(FIRST_NAMES)} {rng.choice(SURNAMES)}"
            rows.append([str(i + 1), fid, person, rng.choice(["Professor", "Associate Professor", "Assistant Professor"])])
        table = rows
        truth.update(issue_date=issue.isoformat(), faculty_count=str(count), faculty_ids=",".join(ids))
    else:
        raise ValueError(f"unknown doc type {doc_type}")

    if variant == "missing_field":
        drop = MISSING_FIELD[doc_type]
        label_for = {"certificate_number": ("NOC No", "Certificate No", "Registration No", "Affidavit No"),
                     "issue_date": ("Date of Affidavit",), "institution_name": ("Name of Institution",)}
        lines = [(lbl, val) for lbl, val in lines if lbl not in label_for[drop]]
        truth.pop(drop, None)
        if drop == "certificate_number":
            qr = None

    pdf = _render(title, subtitle, lines, body, table, qr)
    if variant == "scanned":
        pdf = make_scanned(pdf, rng)
    return GeneratedDoc(doc_type, variant, pdf, truth, list(EXPECTED_RULES[variant]),
                        qr_ref=(qr or {}).get("ref"), issuer=issuer if qr else None, lines=lines)
