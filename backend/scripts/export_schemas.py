"""Export Pydantic schemas to docs/schemas/*.json and the endpoint list to docs/api-contract.md.

Run from backend/:  python -m scripts.export_schemas
"""
import json
from pathlib import Path

from app.main import app
from app.schemas import EXPORTED_SCHEMAS

DOCS_DIR = Path(__file__).resolve().parents[2] / "docs"


def export_json_schemas() -> list[str]:
    out_dir = DOCS_DIR / "schemas"
    out_dir.mkdir(parents=True, exist_ok=True)
    names = []
    for model in EXPORTED_SCHEMAS:
        path = out_dir / f"{model.__name__}.json"
        path.write_text(json.dumps(model.model_json_schema(), indent=2) + "\n", encoding="utf-8")
        names.append(model.__name__)
    return names


def export_api_contract() -> None:
    spec = app.openapi()
    lines = [
        "# VerifyAI API contract",
        "",
        "Generated by `python -m scripts.export_schemas` from backend/. Do not edit by hand.",
        "Full OpenAPI: run the backend and open http://localhost:8000/docs.",
        "Shapes are defined in docs/CONTRACTS.md and docs/schemas/*.json.",
        "",
        "| Method | Path | Summary | Request | Response |",
        "|---|---|---|---|---|",
    ]

    def ref_name(schema: dict | None) -> str:
        if not schema:
            return ""
        if "$ref" in schema:
            return schema["$ref"].split("/")[-1]
        if schema.get("type") == "array" and "$ref" in schema.get("items", {}):
            return f"list[{schema['items']['$ref'].split('/')[-1]}]"
        return schema.get("type", "")

    for path, methods in sorted(spec["paths"].items()):
        for method, op in methods.items():
            req = op.get("requestBody", {}).get("content", {}).get("application/json", {}).get("schema")
            res = op.get("responses", {}).get("200", {}).get("content", {}).get("application/json", {}).get("schema")
            lines.append(f"| {method.upper()} | `{path}` | {op.get('summary', '')} | {ref_name(req)} | {ref_name(res)} |")

    lines += [
        "",
        "Auth: send `Authorization: Bearer <access_token>` from `POST /api/auth/login`.",
        "401 = not authenticated, 403 = role not allowed. Permissions are enforced in the backend.",
        "",
    ]
    (DOCS_DIR / "api-contract.md").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    names = export_json_schemas()
    export_api_contract()
    print(f"Exported {len(names)} schemas to docs/schemas/ and docs/api-contract.md")
